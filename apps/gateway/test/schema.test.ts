// The committed D1 migration must be exactly what Better Auth generates for our options.
// Regenerate after upgrading better-auth or the plugin: UPDATE_SCHEMA=1 npm test.

import { readFileSync, writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { getMigrations } from "better-auth/db/migration";
import { expect, it } from "vitest";
import { authOptions } from "../src/auth";

const FILE = join(dirname(fileURLToPath(import.meta.url)), "../migrations/0001_better_auth.sql");
const HEADER = "-- Generated by test/schema.test.ts from Better Auth + @better-auth/agent-auth. Do not edit.\n";

it("D1 migration matches Better Auth's schema", async () => {
  const database = new DatabaseSync(":memory:");
  const plan = await getMigrations(
    authOptions({ baseURL: "https://gateway.test", database, secret: "schema-generation-only-not-a-real-secret" }),
  );
  expect(plan.unsafeChanges ?? []).toEqual([]);
  const expected = HEADER + (await plan.compileMigrations());
  database.close();
  if (process.env.UPDATE_SCHEMA) writeFileSync(FILE, expected);
  expect(readFileSync(FILE, "utf8")).toBe(expected);
});
