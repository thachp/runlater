import fs from 'node:fs';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import {TOOLS} from '../mcp/tool-schema.mjs';
const ajv = new Ajv({strict: true, code: {source: true, esm: true, lines: true}});
const refs = {};
for (const tool of TOOLS) {ajv.addSchema(tool.inputSchema, tool.name); refs[tool.name] = tool.name;}
const code = '// Generated by scripts/mcp-validators.mjs. Do not edit.\nimport runtime from \'ajv/dist/runtime/ucs2length.js\';\nconst ucs2length = runtime.default;\n' + standaloneCode(ajv, refs).replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, 'ucs2length').trimEnd() + '\n';
const target = new URL('../mcp/tool-validation.generated.mjs', import.meta.url);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== code) throw new Error('MCP validators are stale; run node scripts/mcp-validators.mjs');
} else fs.writeFileSync(target, code);
